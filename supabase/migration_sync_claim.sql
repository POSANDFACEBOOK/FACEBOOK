-- ปัญหาที่แก้: ตอนนี้ทุกแท็บ/ทุกเครื่อง/ทุกแอดมินยิง /api/inbox/sync ตามนาฬิกาของตัวเอง
-- เพจเดียวจึงถูกดึงข้อมูลชุดเดียวกันจาก Facebook ซ้ำหลายรอบต่อนาที จน Facebook จำกัดอัตรา
-- แล้วข้อความหยุดเข้าทั้งเพจ
--
--  sync_claimed_at       = รอบที่กำลังดึงอยู่ (ปลดเป็น NULL เมื่อจบ; ค้างเกิน 90 วิ = รอบนั้นตายแล้ว ให้แย่งได้)
--  last_synced_at        = เวลาเริ่มรอบที่สำเร็จล่าสุด — ใช้ทั้งกันดึงถี่เกิน
--                          และเป็นหลักหมุดว่าต้องไล่รายชื่อแชทย้อนกลับไปถึงไหน (แชทใหม่เกิน 80 อันดับแรกจะได้ไม่ตกหล่น)
--  sync_backlog_at       = จุดที่รอบก่อน "ไล่ไม่ถึง" (ดึงข้อความบางแชทไม่ทัน) — รอบหน้าไล่รายชื่อย้อนไปถึงตรงนี้
--                          แยกจาก last_synced_at เพื่อให้ตัวกันซิงก์ถี่ (45 วิ) ยังทำงานตามปกติ
--  webhook_subscribed_at = ครั้งล่าสุดที่ต่อ webhook สำเร็จ (จะได้ไม่ต้องยิงซ้ำทุกรอบซิงก์)
--
-- ยังไม่รันไฟล์นี้ก็ใช้งานได้ตามปกติ — ระบบจะข้ามการกันซิงก์ซ้ำไปก่อน
-- ════════════════════════════════════════════════════════════════

ALTER TABLE connected_pages
  ADD COLUMN IF NOT EXISTS sync_claimed_at       TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS last_synced_at        TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS sync_backlog_at       TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS webhook_subscribed_at TIMESTAMPTZ;
